// 0: Восток (Вправо)
// 1: Юго-Восток
// 2: Юг (Вниз)
// 3: Юго-Запад
// 4: Запад (Влево)
// 5: Северо-Запад
// 6: Север (Вверх)
// 7: Северо-Восток
export function get8WayDirection(dx: number, dy: number): number {
  // Получаем угол от -PI до PI
  const angle = Math.atan2(dy, dx)

  // Делим на размер одного сектора (45 градусов = PI / 4)
  // Math.round автоматически "притягивает" угол к ближайшему центру сектора
  let index = Math.round(angle / (Math.PI / 4))

  // Убираем отрицательные значения (например, -1 станет 7)
  if (index < 0) {
    index += 8
  }

  // Если индекс получился 8 (ровно 180 градусов), сбрасываем в 0
  return index % 8
}
